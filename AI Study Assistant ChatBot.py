MODEL_NAME = "gemma4:31b"  # Keep this only if it worked in your Ollama test.

def rag_chat(question):

    retrieved_chunks = retrieve_context(question)

    context = "\n\n".join([
        f"File: {item['filename']}\n{item['text']}"
        for item in retrieved_chunks
    ])

    prompt = f"""
You are a helpful AI study assistant.

Answer the question using the document context below.

If the answer is not available in the documents,
clearly say that you could not find it.

DOCUMENT CONTEXT:
{context}

USER QUESTION:
{question}

Give a clear and simple answer.
"""

    response = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {"role": "user", "content": prompt}
        ],
        temperature=0.2
    )

    answer = response.choices[0].message.content

    sources = list(set(
        item["filename"] for item in retrieved_chunks
    ))

    return answer, sources

