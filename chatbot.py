def ask_documind(question):

    previous_question = ""

    if conversation_memory:
        previous_question = conversation_memory[-1]["question"]

    # Connect follow-up questions to the previous topic
    follow_up_words = [
        "it", "its", "that", "this", "there",
        "their", "what about", "and its"
    ]

    is_follow_up = any(
        word in question.lower().split()
        for word in follow_up_words
    ) or "what about" in question.lower()

    retrieval_question = question

    if is_follow_up and previous_question:
        retrieval_question = previous_question + " " + question

    context = retrieve_context_with_sources(
        retrieval_question,
        top_k=3
    )

    # Determine the variable discussed previously
    topic = previous_question.lower()

    # Handle follow-up questions about data types
    if is_follow_up and any(
        word in question.lower()
        for word in ["data type", "type"]
    ):

        fields = ["course", "name", "age", "college", "fee"]

        for field in fields:
            if field in topic:
                pattern = (
                    r'\b' + field +
                    r'\s*=\s*["\']([^"\']+)["\']|' +
                    r'\b' + field +
                    r'\s*=\s*(\d+)'
                )

                match = re.search(pattern, context, re.IGNORECASE)

                if match:
                    if match.group(1) is not None:
                        answer = f"The {field} variable has data type string (str)."
                    else:
                        answer = f"The {field} variable has data type integer (int)."

                    conversation_memory.append({
                        "question": question,
                        "answer": answer
                    })

                    return answer, context, context

    # Direct document fact extraction
    direct_answer = extract_python_answer(
        question,
        context
    )

    if direct_answer:
        answer = direct_answer

    else:
        history = "\n".join(
            f"User: {item['question']}\nAI: {item['answer']}"
            for item in conversation_memory[-3:]
        )

        prompt = f"""
You are DocuMind AI.

Use ONLY the supplied document context.
Use conversation history to understand follow-up questions.
Answer simply and directly.
Do not invent facts.

CONVERSATION HISTORY:
{history}

DOCUMENT CONTEXT:
{context}

QUESTION:
{question}

ANSWER:
"""

        answer = ask_ollama(prompt).strip()

    conversation_memory.append({
        "question": question,
        "answer": answer
    })

    return answer, context, context


